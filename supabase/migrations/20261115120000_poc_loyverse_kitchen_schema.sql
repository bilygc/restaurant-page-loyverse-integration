-- 3. Tables
-- ---------------------------------------------------------------------------

-- 3.1 orders -----------------------------------------------------------------
-- One row per kitchen order, regardless of origin (web or POS). Kitchen state
-- and sync status live ONLY here; Loyverse is never updated with kitchen state.
CREATE TABLE public.orders (
  id                       uuid                     PRIMARY KEY DEFAULT gen_random_uuid(),
  origin                   public.order_origin      NOT NULL,
  kitchen_state            public.kitchen_state     NOT NULL DEFAULT 'nuevo',
  -- NULL until the Loyverse receipt is created (web) / already set (POS).
  loyverse_receipt_number  text,
  sync_status              public.sync_status       NOT NULL DEFAULT 'pending',
  total_centavos           integer                  NOT NULL CHECK (total_centavos >= 0),
  dining_option            text,
  note                     text,
  created_at               timestamptz              NOT NULL DEFAULT now(),
  updated_at               timestamptz              NOT NULL DEFAULT now()
);

-- UNIQUE WHERE NOT NULL (partial unique index). Semantics: many web orders may
-- have a NULL receipt number before sync, but a real receipt number maps to at
-- most one order (H8 dedupe). Because this is a PARTIAL index, an ON CONFLICT
-- dedupe must include the predicate, e.g.:
--   ON CONFLICT (loyverse_receipt_number)
--     WHERE loyverse_receipt_number IS NOT NULL DO NOTHING
-- The current API dedupes via a SELECT (getOrderByReceiptNumber) and via the
-- loyverse_webhook_events.receipt_number UNIQUE constraint instead.
CREATE UNIQUE INDEX orders_loyverse_receipt_number_key
  ON public.orders (loyverse_receipt_number)
  WHERE loyverse_receipt_number IS NOT NULL;

-- Serves the /cocina board read: filter by kitchen_state, order by created_at.
CREATE INDEX orders_kitchen_state_created_at_idx
  ON public.orders (kitchen_state, created_at);

-- 3.2 order_items ------------------------------------------------------------
-- Snapshot of name + unit price AS SOLD (never a live price reference).
-- item_name / unit_price_centavos are NOT NULL so kitchen can always render a
-- line even if the menu changes later.
CREATE TABLE public.order_items (
  id                    uuid      PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id              uuid      NOT NULL,
  menu_item_id          text,
  variant_id            text,
  item_name             text      NOT NULL,
  quantity              integer   NOT NULL DEFAULT 1 CHECK (quantity > 0),
  unit_price_centavos   integer   NOT NULL CHECK (unit_price_centavos >= 0),
  line_note             text,
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now(),
  -- Explicit name so generated types report exactly "order_items_order_id_fkey".
  CONSTRAINT order_items_order_id_fkey FOREIGN KEY (order_id)
    REFERENCES public.orders (id) ON DELETE CASCADE
);

-- FK index (Postgres does not create these automatically).
CREATE INDEX order_items_order_id_idx ON public.order_items (order_id);

-- 3.3 loyverse_item_mappings -------------------------------------------------
-- Lookup from our menu_item_id to Loyverse variant ids (mapping BY variant_id,
-- per oracle). reference_variant_id is the second id carried by the mapping;
-- the POC API currently uses a static pricelist and does not read this table
-- yet — it exists for the human tester / future DB-backed mapping (see seed).
CREATE TABLE public.loyverse_item_mappings (
  id                    uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  menu_item_id          text        NOT NULL UNIQUE,
  loyverse_variant_id   text        NOT NULL,
  reference_variant_id  text        NOT NULL,
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now()
);

-- 3.4 loyverse_webhook_events ------------------------------------------------
-- Raw received events, deduped by receipt_number (UNIQUE) for H8. The webhook
-- body is UNTRUSTED and stored only as a trigger/audit payload; canonical data
-- is re-fetched via GET /receipts before anything is trusted (ADR 0001).
CREATE TABLE public.loyverse_webhook_events (
  id              uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  receipt_number  text        NOT NULL UNIQUE,
  payload         jsonb       NOT NULL,
  processed       boolean     NOT NULL DEFAULT false,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);

-- 3.5 outbox_jobs ------------------------------------------------------------
-- Transactional outbox for create_receipt retries (flow D / H6). A failed
-- Loyverse call never blocks payment: the order is already persisted and the
-- worker retries this row until done / failed.
CREATE TABLE public.outbox_jobs (
  id             uuid                       PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id       uuid                       NOT NULL,
  type           public.outbox_job_type     NOT NULL DEFAULT 'create_receipt',
  status         public.outbox_job_status   NOT NULL DEFAULT 'pending',
  attempts       integer                    NOT NULL DEFAULT 0,
  next_retry_at  timestamptz                NOT NULL DEFAULT now(),
  last_error     text,
  created_at     timestamptz                NOT NULL DEFAULT now(),
  updated_at     timestamptz                NOT NULL DEFAULT now(),
  -- Explicit name so generated types report exactly "outbox_jobs_order_id_fkey".
  CONSTRAINT outbox_jobs_order_id_fkey FOREIGN KEY (order_id)
    REFERENCES public.orders (id) ON DELETE CASCADE
);

-- FK index (Postgres does not create these automatically).
CREATE INDEX outbox_jobs_order_id_idx ON public.outbox_jobs (order_id);

-- Required worker index: claimOutboxJobs does
--   WHERE status = 'pending' AND next_retry_at <= now()
--   ORDER BY next_retry_at ASC LIMIT n
CREATE INDEX outbox_jobs_status_next_retry_at_idx
  ON public.outbox_jobs (status, next_retry_at);

-- ---------------------------------------------------------------------------
-- 4. updated_at triggers (one per table; shared function)
-- ---------------------------------------------------------------------------
CREATE TRIGGER orders_set_updated_at
  BEFORE UPDATE ON public.orders
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER order_items_set_updated_at
  BEFORE UPDATE ON public.order_items
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER loyverse_item_mappings_set_updated_at
  BEFORE UPDATE ON public.loyverse_item_mappings
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER loyverse_webhook_events_set_updated_at
  BEFORE UPDATE ON public.loyverse_webhook_events
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER outbox_jobs_set_updated_at
  BEFORE UPDATE ON public.outbox_jobs
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- ---------------------------------------------------------------------------
-- 5. Row Level Security — enable on ALL five public tables, NO policies.
--    Default-deny for anon / authenticated; service_role BYPASSes RLS.
--    (FORCE RLS deliberately omitted.) No anon/authenticated direct access.
-- ---------------------------------------------------------------------------
ALTER TABLE public.orders                  ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_items             ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.loyverse_item_mappings  ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.loyverse_webhook_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.outbox_jobs             ENABLE ROW LEVEL SECURITY;
