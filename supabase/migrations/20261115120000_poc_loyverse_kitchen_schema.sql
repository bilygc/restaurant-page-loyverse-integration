-- 1. Enums (order matters only for readability; all created before tables)
-- ---------------------------------------------------------------------------
CREATE TYPE public.order_origin AS ENUM ('web', 'pos');
CREATE TYPE public.kitchen_state AS ENUM ('nuevo', 'en_preparacion', 'listo', 'entregado');
CREATE TYPE public.sync_status AS ENUM ('pending', 'synced', 'failed');
CREATE TYPE public.outbox_job_type AS ENUM ('create_receipt');
CREATE TYPE public.outbox_job_status AS ENUM ('pending', 'processing', 'done', 'failed');

-- ---------------------------------------------------------------------------
-- 2. Shared updated_at trigger function
--    `supabase gen types` exposes this as public.Functions.set_updated_at with
--    Args: Record<PropertyKey, never> and Returns: unknown (RETURNS trigger).
--    SET search_path = '' keeps the function lint-clean (no mutable path);
--    now() resolves via the implicitly-searched pg_catalog.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

